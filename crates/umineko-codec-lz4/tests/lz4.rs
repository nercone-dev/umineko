fn cases() -> Vec<(&'static str, Vec<u8>, &'static [u8])> {
    [
        ("empty", Vec::new(), EMPTY.as_slice()),
        ("byte", b"a".to_vec(), BYTE.as_slice()),
        ("short", b"hello".to_vec(), SHORT.as_slice()),
        ("twelve", vec![b'a'; 12], TWELVE.as_slice()),
        ("thirteen", vec![b'a'; 13], THIRTEEN.as_slice()),
        ("runs", vec![b'a'; 5000], RUNS.as_slice()),
        ("text", text(20000), TEXT.as_slice()),
        ("noise", noise(4000), NOISE.as_slice()),
    ]
    .to_vec()
}

#[test]
fn decodes_blocks_the_reference_library_wrote() {
    let codec = LZ4::default();
    for (name, data, encoded) in cases() {
        assert_eq!(codec.decode(encoded).unwrap(), data, "{name}");
    }
}

#[test]
fn round_trips_every_shape() {
    let codec = LZ4::default();
    for (name, data, _) in cases() {
        let encoded = codec.compress(&data).unwrap();
        assert_eq!(codec.decompress(&encoded).unwrap(), data, "{name}");
    }
}

#[test]
fn repeats_shrink() {
    let codec = LZ4::default();
    let data = text(20000);
    let encoded = codec.encode(&data).unwrap();
    assert!(encoded.len() < data.len() / 8, "{} vs {}", encoded.len(), data.len());
}

#[test]
fn short_blocks_stay_literal() {
    let codec = LZ4::default();
    for length in 0..13 {
        let data = vec![b'a'; length];
        let encoded = codec.encode(&data).unwrap();
        assert_eq!(encoded.len(), length + 1 + usize::from(length >= 15), "at {length}");
        assert_eq!(codec.decode(&encoded).unwrap(), data);
    }
}

#[test]
fn a_broken_stream_is_refused() {
    let codec = LZ4::default();
    assert_eq!(codec.decode(&[0x50]), Err(LZ4Error::Truncated));
    assert_eq!(codec.decode(&[0x10, b'a', 0x05, 0x00]), Err(LZ4Error::Format));
    assert_eq!(codec.decode(&[0x10, b'a', 0x00, 0x00]), Err(LZ4Error::Format));
}

#[test]
fn a_limit_stops_a_bomb() {
    let bomb = LZ4::default().encode(&vec![0; 5000]).unwrap();
    let codec = LZ4 { limit: Some(1000), ..LZ4::default() };
    assert_eq!(codec.decode(&bomb), Err(LZ4Error::Limit));
}

#[test]
fn streaming_matches_the_one_shot_call() {
    let codec = LZ4::default();
    let data = text(5000);
    let mut encoder = codec.encoder();
    for chunk in data.chunks(211) {
        encoder.update(chunk).unwrap();
    }
    let encoded = encoder.finalize().unwrap();
    assert_eq!(encoded, codec.compress(&data).unwrap());
    let mut decoder = codec.decoder();
    decoder.update(&encoded).unwrap();
    assert_eq!(decoder.finalize().unwrap(), data);
}
