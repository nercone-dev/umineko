#[test]
fn xxh32_matches_the_reference() {
    for (index, length) in LENGTHS.iter().enumerate() {
        let data = data(*length);
        assert_eq!(u32::from_be_bytes(XXH32::digest(&data)), XXH32_VECTORS[index], "at {length}");
        assert_eq!(XXH32::hash(&data, 42), XXH32_SEEDED[index], "seeded at {length}");
    }
}

