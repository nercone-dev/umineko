#[test]
fn xxh3_carries_a_seed() {
    for (index, length) in LENGTHS.iter().enumerate() {
        let data = data(*length);
        let mut hash = XXH3_64::builtin(42);
        hash.update(&data);
        assert_eq!(u64::from_be_bytes(hash.finalize()), XXH3_64_SEEDED[index], "at {length}");
        let mut wide = XXH3_128::builtin(42);
        wide.update(&data);
        assert_eq!(u128::from_be_bytes(wide.finalize()), XXH3_128_SEEDED[index], "at {length}");
    }
}

#[test]
fn streaming_matches_the_one_shot_call() {
    let data = data(10000);
    for split in [0, 1, 63, 64, 65, 127, 128, 191, 192, 239, 240, 241, 255, 256, 257, 1023, 1024, 4096, 9999, 10000] {
        let mut xxh32 = XXH32::new();
        xxh32.update(&data[..split]);
        xxh32.update(&data[split..]);
        assert_eq!(xxh32.finalize(), XXH32::digest(&data), "XXH32 at {split}");

        let mut xxh64 = XXH64::new();
        xxh64.update(&data[..split]);
        xxh64.update(&data[split..]);
        assert_eq!(xxh64.finalize(), XXH64::digest(&data), "XXH64 at {split}");

        let mut xxh3 = XXH3_64::new();
        xxh3.update(&data[..split]);
        xxh3.update(&data[split..]);
        assert_eq!(xxh3.finalize(), XXH3_64::digest(&data), "XXH3-64 at {split}");

        let mut wide = XXH3_128::new();
        wide.update(&data[..split]);
        wide.update(&data[split..]);
        assert_eq!(wide.finalize(), XXH3_128::digest(&data), "XXH3-128 at {split}");
    }
}

#[test]
fn streaming_matches_the_one_shot_call_at_every_length() {
    let data = data(2100);
    for length in 0..data.len() {
        let mut hash = XXH3_64::new();
        for chunk in data[..length].chunks(37) {
            hash.update(chunk);
        }
        assert_eq!(hash.finalize(), XXH3_64::digest(&data[..length]), "at {length}");
    }
}

#[test]
fn reset_restores_the_seeded_state() {
    let mut hash = XXH3_64::builtin(42);
    hash.update(&data(1000));
    hash.reset();
    hash.update(b"abc");
    let mut fresh = XXH3_64::builtin(42);
    fresh.update(b"abc");
    assert_eq!(hash.finalize(), fresh.finalize());
}
