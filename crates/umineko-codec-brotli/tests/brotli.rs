#[test]
fn round_trips_every_shape() {
    let codec = Brotli::default();
    for data in [Vec::new(), b"a".to_vec(), b"hello world".to_vec(), vec![b'a'; 5000], text(200000)] {
        let encoded = codec.compress(&data).unwrap();
        assert_eq!(codec.decompress(&encoded).unwrap(), data, "length {}", data.len());
    }
}

#[test]
fn every_window_round_trips() {
    for window in [10, 16, 17, 18, 22, 24] {
        let codec = Brotli { window, ..Brotli::default() };
        let data = text(3000);
        let encoded = codec.encode(&data).unwrap();
        assert_eq!(Brotli::default().decode(&encoded).unwrap(), data, "window {window}");
    }
}

#[test]
fn reads_the_uncompressed_streams_the_reference_library_wrote() {
    let codec = Brotli::default();
    assert_eq!(codec.decode(&EMPTY).unwrap(), b"");
    assert_eq!(codec.decode(&SHORT).unwrap(), b"hello world");
}

#[test]
fn reads_the_prefix_coded_streams_the_reference_library_wrote() {
    assert_eq!(Brotli::default().decode(&TEXT).unwrap(), text(4000));
}

#[test]
fn a_broken_stream_is_refused() {
    let codec = Brotli::default();
    assert_eq!(codec.decode(&[]), Err(BrotliError::Truncated));
    assert_eq!(codec.decode(&[0x21]), Err(BrotliError::Truncated));
}

#[test]
fn a_limit_stops_a_bomb() {
    let bomb = Brotli::default().encode(&vec![0; 5000]).unwrap();
    let codec = Brotli { limit: Some(1000), ..Brotli::default() };
    assert_eq!(codec.decode(&bomb), Err(BrotliError::Limit));
}

#[test]
fn streaming_matches_the_one_shot_call() {
    let codec = Brotli::default();
    let data = text(5000);
    let mut encoder = codec.encoder();
    for chunk in data.chunks(211) {
        encoder.update(chunk).unwrap();
    }
    let encoded = encoder.finalize().unwrap();
    assert_eq!(encoded, codec.compress(&data).unwrap());
    let mut decoder = codec.decoder();
    decoder.update(&encoded).unwrap();
    assert_eq!(decoder.finalize().unwrap(), data);
}

