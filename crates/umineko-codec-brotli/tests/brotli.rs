#[test]
fn a_prefix_code_reads_back_as_the_code_it_names() {
    for shape in [[3u32, 1, 1, 5].to_vec(), (0..256).map(|index| (index % 7 + 1) as u32).collect(), (0..704).map(|index| match index % 53 { 0 => 9u32, 1 => 2, _ => 0 }).collect()] {
        let code = BrotliCode::from_frequencies(&shape).unwrap();
        let mut writer = BrotliWriter::new();
        code.write(&mut writer).unwrap();
        for (symbol, frequency) in shape.iter().enumerate().filter(|(_, frequency)| **frequency > 0) {
            code.encode(&mut writer, symbol).unwrap();
            let _ = frequency;
        }
        let bytes = writer.finish();
        let mut reader = umineko_codec_brotli::BrotliReader::new(&bytes);
        let back = BrotliCode::read(&mut reader, shape.len()).unwrap();
        for (symbol, _) in shape.iter().enumerate().filter(|(_, frequency)| **frequency > 0) {
            assert_eq!(back.symbol(&mut reader).unwrap(), symbol, "alphabet of {}", shape.len());
        }
    }
}

#[test]
fn commands_cover_every_byte_of_the_content_they_carry() {
    let codec = Brotli::default();
    for (name, data) in [("english", english(60000)), ("noise", noise(20000)), ("text", text(60000))] {
        let mut matcher = umineko_codec_lz77::LZ77Matcher::new(Brotli::backward(codec.window()), Brotli::MAXIMUM_COPY, data.len()).with_probes(codec.probes());
        let commands = codec.commands(&data, 0, data.len(), &mut matcher);
        let mut offset = 0;
        for command in commands.iter() {
            offset += command.literals;
            if command.distance == 0 {
                continue;
            }
            assert!(command.distance <= offset, "{name} reaches back past the start");
            assert!(command.copy >= Brotli::MINIMUM_COPY, "{name} names a copy shorter than the format allows");
            offset += command.copy;
        }
        assert_eq!(offset, data.len(), "{name} loses bytes");
        assert!(commands.iter().all(|command| command.codes().is_ok()), "{name} names a command the format has no symbol for");
    }
    let single = BrotliCommand { literals: 0, distance: 4, copy: 2 };
    assert_eq!(single.codes().unwrap(), (128, 0, 0), "the smallest command is written as symbol 128");
}
