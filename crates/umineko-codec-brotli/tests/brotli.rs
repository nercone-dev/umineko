fn text(length: usize) -> Vec<u8> {
    let words = ["alpha ", "beta ", "gamma ", "delta "];
    let mut data = Vec::new();
    while data.len() < length {
        data.extend_from_slice(words[data.len() % words.len()].as_bytes());
    }
    data.truncate(length);
    data
}

