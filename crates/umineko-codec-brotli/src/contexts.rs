    /// The model the two bits of a meta-block header name.
    pub fn from_bits(bits: u64) -> Result<Self, BrotliError> {
        match bits {
            0 => Ok(Self::LSB6),
            1 => Ok(Self::MSB6),
            2 => Ok(Self::UTF8),
            3 => Ok(Self::Signed),
            _ => Err(BrotliError::Format),
        }
    }

    /// The two bits a meta-block header names this model with.
    pub fn bits(&self) -> u64 {
        match self {
            Self::LSB6 => 0,
            Self::MSB6 => 1,
            Self::UTF8 => 2,
            Self::Signed => 3,
        }
    }

    /// The context the last two bytes of the output name under this model.
    pub fn id(&self, first: u8, second: u8) -> usize {
        let table = self.bits() as usize * 512;
        (Self::LOOKUP[table + first as usize] | Self::LOOKUP[table + 256 + second as usize]) as usize
    }
